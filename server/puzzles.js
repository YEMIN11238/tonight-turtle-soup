export function getPuzzle(id) {
  return PUZZLES.find((p) => p.id === id);
}

// 校验：每题 weight 之和为 100，至少一条 core。
export function validatePuzzle(p) {
  const sum = p.facts.reduce((s, f) => s + f.weight, 0);
  const errs = [];
  if (sum !== 100) errs.push(`${p.id}: weight 之和为 ${sum}`);
  if (!p.facts.some((f) => f.core)) errs.push(`${p.id}: 没有 core 事实`);
  const ids = new Set(p.facts.map((f) => f.id));
  if (ids.size !== p.facts.length) errs.push(`${p.id}: fact id 重复`);
  return errs;
}
